const TYPE_ADVANTAGES: Record<ElementType, ElementType[]> = {
  Fire: ['Grass', 'Ice'],
  Water: ['Fire', 'Rock'],
  Grass: ['Water', 'Rock'],
  Electric: ['Water', 'Ice'],
  Rock: ['Fire', 'Electric', 'Ice'],
  Psychic: ['Dragon', 'Rock'],
  Dragon: ['Dragon', 'Electric'],
  Ice: ['Dragon', 'Grass'],
};

export function getTypeMultiplier(attacker: ElementType, defender: ElementType): number {
  if (TYPE_ADVANTAGES[attacker]?.includes(defender)) return 1.35;
  if (TYPE_ADVANTAGES[defender]?.includes(attacker)) return 0.78;
  return 1.0;
}

