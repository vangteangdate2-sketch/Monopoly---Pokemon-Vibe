export function generateDailyChallenges(dateKey: string): DailyChallenge[] {
  // Deterministic daily rotation based on YYYY-MM-DD
  const seed = dateKey.split('').reduce((acc, ch) => acc + ch.charCodeAt(0), 0);
  const templates: Omit<DailyChallenge, 'progress' | 'claimed'>[] = [
    {
      id: `battle_${dateKey}`,
      title: 'Gym Challenger',
      description: 'Win 2 Pokémon card battles to seize or claim territory.',
      target: 2,
      rewardMoney: 300,
      rewardXp: 180,
      metric: 'battlesWon',
    },
    {
      id: `badges_${dateKey}`,
      title: 'Regional Collector',
      description: 'Hold at least 3 Gym Badges during a match.',
      target: 3,
      rewardMoney: 350,
      rewardXp: 220,
      metric: 'badgesCollected',
    },
    {
      id: `trade_${dateKey}`,
      title: 'Legendary Broker',
      description: 'Complete 1 Legendary Pokémon trade or vault claim.',
      target: 1,
      rewardMoney: 400,
      rewardXp: 260,
      metric: 'tradesCompleted',
    },
    {
      id: `wealth_${dateKey}`,
      title: 'Poké Tycoon',
      description: 'Reach 2,200₽ in combined cash and Badge asset value.',
      target: 2200,
      rewardMoney: 250,
      rewardXp: 200,
      metric: 'netWorth',
    },
  ];
  // Rotate first 3 or return all 4 with slight daily bonus variance
  return templates.map((t, idx) => ({
    ...t,
    rewardXp: t.rewardXp + ((seed + idx * 17) % 40),
    progress: 0,
    claimed: false,
  }));
}

